"""
Geography (2026-11-03): where everyone is, how long it takes to get anywhere, and what's in the way.

Why code owns this: language models are poor at working out routes and distances from a map written
out as text - they invent shortcuts, lose track of who is where, and forget that a raised bridge cuts
the Vyborg side off (see "Talk like a Graph", Fatemi et al. 2023, and the PLUGH benchmark, 2024). The
same models do well when a symbolic module does that part and they only choose destinations by name
(Fang et al. 2024, "Large Language Models Are Neurosymbolic Reasoners"; Park et al. 2023, "Generative
Agents", which keeps the world as a tree of named areas and moves agents with ordinary pathfinding).
So: the GM names a place, this module routes over a graph, times the trip, applies what blocks it, and
tells the GM the result in a few plain sentences.

Data: settings/<key>/geography.json (for Petrograd it's generated by tools/build_petrograd_geography.py)
  nodes {id: {name, kind, scale city|country, area, lat, lng, note?}}
  edges {id: {a, b, mode street|road|bridge|rail|sea, km, name?, raisable?, closed_at_start?}}
  speeds_kmh {foot: {default, <unit kind>...}, rail, sea}, boarding_hours {rail, sea}
  same_scene_hours: trips at most this long finish within the current beat
  areas {area: description}, player_start, initial_positions {unit_id: node}

State: state["geo"] = {
  "player": node,
  "positions": {unit_id: node},              # where a unit is (its last node, if on the move)
  "moving": {unit_id: {to, path, legs, hours_left, departed, eta}},
  "edges": {edge_id: {status, by?, since?, reason?}},   # only edges that differ from open
}
Edge status: open | raised (bridges) | cut (rail: no trains, men can still march along the line) |
blocked (nothing passes). Separately an edge can be HELD by a unit: a picket that stops the other
side's movements (not its own) until someone clears it with resolve_confrontation.
"""

import difflib
import heapq
import json
import math
import unicodedata
from datetime import date, timedelta
from pathlib import Path

SETTINGS_DIR = Path(__file__).resolve().parent / "settings"
REACH_HOURS = 1.5         # a unit this close (on foot, by an open way) can join a fight at a place
ACT_HOURS = 0.25          # ...and this close to an edge's end can raise / cut / hold it
FOOT_MODES = {"street", "road", "bridge"}
STATUSES = {"open", "raised", "cut", "blocked"}
PLAYER = "player"

_CACHE = {}


def load(setting_key):
    if setting_key in _CACHE:
        return _CACHE[setting_key]
    path = SETTINGS_DIR / str(setting_key) / "geography.json"
    geo = None
    if path.exists():
        geo = json.loads(path.read_text(encoding="utf-8"))
        geo["_adj"] = {n: [] for n in geo["nodes"]}
        for eid, e in geo["edges"].items():
            geo["_adj"][e["a"]].append((eid, e["b"]))
            geo["_adj"][e["b"]].append((eid, e["a"]))
        geo["_names"] = {}
        for nid, n in geo["nodes"].items():
            for alias in [nid, n["name"], *n.get("aliases", [])]:
                geo["_names"].setdefault(_norm(alias), nid)
    _CACHE[setting_key] = geo
    return geo


def _norm(text):
    text = unicodedata.normalize("NFKD", str(text)).encode("ascii", "ignore").decode().lower()
    for junk in ("the ", "(", ")", ",", "."):
        text = text.replace(junk, " ")
    return " ".join(text.replace("_", " ").replace("-", " ").split())


# ---------------------------------------------------------------- state

def force_units(state):
    """Every unit in every forces tracker, by id."""
    out = {}
    for m in (state.get("mechanics") or {}).values():
        if m.get("render_primitive") == "forces":
            for u in (m.get("data") or {}).get("units") or []:
                out[u["id"]] = u
    return out


def find_unit(state, uid):
    """(tracker instance id, unit dict) for a unit id in any forces tracker, or (None, None)."""
    for iid, m in (state.get("mechanics") or {}).items():
        if m.get("render_primitive") == "forces":
            for u in (m.get("data") or {}).get("units") or []:
                if u["id"] == uid:
                    return iid, u
    return None, None


def _uname(state, uid):
    return (force_units(state).get(uid) or {}).get("name", uid)


def ensure_initialized(state, geo):
    if not geo:
        return None
    g = state.setdefault("geo", {})
    g.setdefault("player", geo.get("player_start"))
    g.setdefault("moving", {})
    if "edges" not in g:
        g["edges"] = {eid: {"status": "cut" if e["mode"] == "rail" else "blocked", "reason": e["closed_at_start"]}
                      for eid, e in geo["edges"].items() if e.get("closed_at_start")}
    pos = g.setdefault("positions", {})
    units = force_units(state)
    for uid in units:
        if uid not in pos and uid in (geo.get("initial_positions") or {}):
            pos[uid] = geo["initial_positions"][uid]
    for uid in [u for u in pos if u not in units]:  # disbanded, destroyed, or dropped from a tracker
        pos.pop(uid)
    for uid in [u for u in g["moving"] if u not in units]:
        g["moving"].pop(uid)
    g.setdefault("schedule_done", [])
    return g


def edge_state(state, eid):
    return ((state.get("geo") or {}).get("edges") or {}).get(eid) or {"status": "open"}


def side_of(state, who):
    """+1 for the player's side, -1 against, 0 for units sitting it out."""
    if who == PLAYER:
        return 1
    u = force_units(state).get(who)
    if not u:
        return 0
    lo = u.get("loyalty", 0)
    return 1 if lo >= 1 else -1 if lo <= -1 else 0


# ---------------------------------------------------------------- places

def resolve_place(geo, state, text):
    """A node id from what the GM wrote: an id, a name, or a unit (meaning wherever that unit is).
    Returns (node_id, None) or (None, error message with the nearest names)."""
    if not text:
        return None, "no place given"
    key = _norm(text)
    if key in geo["_names"]:
        return geo["_names"][key], None
    g = state.get("geo") or {}
    if key in (PLAYER, "me", "here", "player"):
        return g.get("player"), None
    units = force_units(state)
    for uid, u in units.items():
        if key in (_norm(uid), _norm(u.get("name", ""))) and (g.get("positions") or {}).get(uid):
            return g["positions"][uid], None
    hits = list(dict.fromkeys(nid for name, nid in geo["_names"].items() if key and (key in name or name in key) and len(name) > 3))
    if len(hits) > 1:  # "Smolny" means the Smolny Institute, not the Smolny end of a bridge
        hits = [h for h in hits if geo["nodes"][h]["kind"] != "bridgehead"] or hits
    if len(hits) > 1:
        starts = [h for h in hits if _norm(geo["nodes"][h]["name"]).startswith(key)]
        hits = starts if len(starts) == 1 else hits
    if len(hits) == 1:
        return hits[0], None
    names = {geo["nodes"][nid]["name"] for nid in set(hits)} or {
        geo["nodes"][geo["_names"][n]]["name"] for n in difflib.get_close_matches(key, geo["_names"].keys(), n=4, cutoff=0.5)}
    return None, f"Unknown place '{text}'." + (f" Did you mean: {', '.join(sorted(names))}?" if names else " Use a name from GEOGRAPHY.")


def place_name(geo, nid):
    return geo["nodes"][nid]["name"] if nid in geo["nodes"] else str(nid)


def area_name(geo, nid):
    area = geo["nodes"].get(nid, {}).get("area")
    return (geo.get("areas") or {}).get(area, area or "")


# ---------------------------------------------------------------- routing

def _speed(geo, state, who):
    foot = geo["speeds_kmh"]["foot"]
    if who == PLAYER:
        return foot.get("player", foot["default"])
    kind = (force_units(state).get(who) or {}).get("kind")
    return foot.get(kind, foot["default"])


def _month(state):
    return str(state.get("date") or "")[5:7]


def frozen(geo, state, key):
    return _month(state) in ((geo.get("freeze") or {}).get(key) or [])


def _passable(state, eid, edge, mode, who_side):
    """Can a mover of this side use this edge in this way ('foot', 'train', 'ship')?"""
    st = edge_state(state, eid)
    status = st.get("status", "open")
    if status in ("raised", "blocked"):
        return False, f"{edge.get('name') or 'the way'} is {status}"
    if status == "cut" and mode == "train":
        return False, f"the line ({edge.get('name', 'rail')}) is cut"
    holder = st.get("held_by")
    if holder and who_side is not None:
        hs = side_of(state, holder)
        if hs and hs != who_side:
            return False, f"{edge.get('name') or 'the way'} is held by {holder}"
    return True, None


def route(geo, state, start, goal, who=PLAYER, foot_only=False):
    """Fastest way from start to goal for this mover, respecting edge states. Returns a dict with
    hours, path (node ids), legs [(edge_id, how, hours)], and 'avoided' (blocks the route went round),
    or None if there is no way through."""
    if start == goal:
        return {"hours": 0.0, "path": [start], "legs": [], "avoided": []}
    speed = _speed(geo, state, who)
    who_side = side_of(state, who)
    rail_kmh, sea_kmh = geo["speeds_kmh"]["rail"], geo["speeds_kmh"]["sea"]
    river_kmh = geo["speeds_kmh"].get("river", sea_kmh)
    board = geo.get("boarding_hours") or {}
    # Past a short walk, men march about 8 hours a day: a long leg on foot costs its days, not its
    # walking hours (24/8 = 3x). Trains and ships run around the clock.
    march = 24.0 / geo.get("march_hours_per_day", 24)
    long_km = geo.get("long_march_km", 1e9)
    river_shut = frozen(geo, state, "river")
    ice_walk = frozen(geo, state, "sea_ice_walk")
    avoided = set()
    # Dijkstra over (node, how we arrived) so boarding a train or a ship costs once, not per leg
    frontier = [(0.0, 0, start, "foot")]
    best = {(start, "foot"): 0.0}
    back = {}
    tie = 0
    while frontier:
        cost, _, node, how = heapq.heappop(frontier)
        if node == goal:
            legs, path, key = [], [goal], (node, how)
            while key in back:
                prev_key, eid, leg_how, leg_hours = back[key]
                legs.append((eid, leg_how, leg_hours))
                path.append(prev_key[0])
                key = prev_key
            return {"hours": round(cost, 2), "path": path[::-1], "legs": legs[::-1], "avoided": avoided}
        if cost > best.get((node, how), math.inf):
            continue
        for eid, nxt in geo["_adj"][node]:
            e = geo["edges"][eid]
            options = []
            walk = e["km"] / speed * (march if e["km"] > long_km else 1)
            if e["mode"] in FOOT_MODES:
                options.append(("foot", walk))
            elif e["mode"] == "rail":
                options.append(("train", e["km"] / rail_kmh + (0 if how == "train" else board.get("rail", 0))))
                options.append(("foot", walk))  # march along the line
            elif e["mode"] == "sea":
                # winter: icebreakers keep the Gulf open, slowly - and the ice off Kronstadt bears men
                slow = 2 if e.get("freezes") and ice_walk else 1
                options.append(("ship", slow * e["km"] / sea_kmh + (0 if how == "ship" else board.get("sea", 0))))
                if e.get("ice_walk") and ice_walk:
                    options.append(("ice", e["km"] / speed))
            elif e["mode"] == "river" and not river_shut:
                options.append(("ship", e["km"] / river_kmh + (0 if how == "ship" else board.get("river", 0))))
            for leg_how, hours in options:
                if foot_only and leg_how not in ("foot", "ice"):
                    continue
                ok, why = _passable(state, eid, e, leg_how, who_side)
                if not ok:
                    avoided.add(why)
                    continue
                c = cost + hours
                if c < best.get((nxt, leg_how), math.inf):
                    best[(nxt, leg_how)] = c
                    back[(nxt, leg_how)] = ((node, how), eid, leg_how, hours)
                    tie += 1
                    heapq.heappush(frontier, (c, tie, nxt, leg_how))
    return None


def route_noted(geo, state, start, goal, who=PLAYER, foot_only=False):
    """route(), with 'avoided' trimmed to the blocks that actually cost this trip time (a raised
    bridge on the far side of town is not worth mentioning on the way to Pskov)."""
    r = route(geo, state, start, goal, who, foot_only)
    if r is None or not r["avoided"]:
        if r is not None:
            r["avoided"] = []
        return r
    blocks = blocks_near(geo, state, start, goal, who)
    saved = state["geo"]["edges"]
    state["geo"]["edges"] = {}
    try:
        free = route(geo, state, start, goal, who, foot_only)
    finally:
        state["geo"]["edges"] = saved
    r["avoided"] = (blocks[:3] + ([f"and {len(blocks) - 3} more"] if len(blocks) > 3 else [])) if free and free["hours"] < r["hours"] - 0.05 else []
    return r


def describe_route(geo, r):
    """'on foot over the Liteyny Bridge, then by train on the Nikolaevsky line' - the parts that
    matter, not every street corner."""
    parts, last = [], None
    for eid, how, _ in r["legs"]:
        e = geo["edges"].get(eid) or {"mode": eid}
        if eid == "muster":
            bit = "mustering"
        elif how == "train":
            bit = f"by train ({e.get('name', 'rail')})"
        elif how == "ice":
            bit = "across the ice"
        elif how == "ship" and e["mode"] == "river":
            bit = f"by river steamer ({e.get('name', 'river')})"
        elif how == "ship":
            bit = "by ship"
        elif e["mode"] == "bridge":
            bit = f"over the {e['name']}"
        elif e["mode"] == "rail":
            bit = f"marching along the {e.get('name', 'line')}"
        elif e["mode"] == "road" and e.get("km", 0) > 15:
            bit = "marching by road"
        else:
            bit = "on foot"
        if bit != last:
            parts.append(bit)
        last = bit
    return ", ".join(dict.fromkeys(parts)) or "already there"


def fmt_hours(hours):
    if hours < 1:
        return f"{max(5, int(round(hours * 60 / 5) * 5))} minutes"
    if hours < 20:
        h = round(hours * 2) / 2
        return f"{h:g} hours" if h != 1 else "1 hour"
    days = hours / 24
    return f"{days:.1f} days" if days < 3 else f"{round(days)} days"


# ---------------------------------------------------------------- movement

def _add_days(iso, days):
    return (date.fromisoformat(iso) + timedelta(days=days)).isoformat()


def muster_hours(unit):
    """Time for a unit to turn out, draw ammunition and get moving before the first step: an hour or
    so for a keen battalion, most of a day for a big, slack one."""
    readiness = unit.get("readiness", 3)
    size = max(0.25, (unit.get("strength", 1000) / 2000) ** 0.5)
    return round(min(12.0, max(0.25, (6 - readiness) * 0.75 * size)), 2)


def move(geo, state, who, to_text, foot_only=False):
    """Moves a unit or the player toward a place. Short trips finish now; longer ones put the unit on
    the road and it arrives as the clock advances (tick_day). Returns a result dict for the GM."""
    g = ensure_initialized(state, geo)
    units = force_units(state)
    if who != PLAYER and who not in units:
        return {"error": f"Unknown unit '{who}'. Use an id from the forces tracker, or 'player'."}
    goal, err = resolve_place(geo, state, to_text)
    if err:
        return {"error": err}
    start = g["player"] if who == PLAYER else g["positions"].get(who)
    if start is None:  # a unit the tracker added mid-campaign: it appears where the GM says
        g["positions"][who] = goal
        return {"unit": who, "placed_at": place_name(geo, goal), "note": "First placement - no travel time."}
    r = route_noted(geo, state, start, goal, who, foot_only)
    if r is None:
        return {"error": f"No way through from {place_name(geo, start)} to {place_name(geo, goal)} right now.",
                "blocked_by": blocks_near(geo, state, start, goal, who)}
    already_marching = who in g["moving"]
    muster = 0.0 if who == PLAYER or already_marching or start == goal else muster_hours(units[who])
    if muster:
        r["legs"].insert(0, ("muster", "muster", muster))
        r["hours"] = round(r["hours"] + muster, 2)
    result = {"unit": who, "from": place_name(geo, start), "to": place_name(geo, goal),
              "travel": fmt_hours(r["hours"]), "hours": r["hours"], "route": describe_route(geo, r)}
    if muster:
        result["muster"] = f"{fmt_hours(muster)} to turn out and get moving (included)"
    if r["avoided"]:
        result["went_round"] = r["avoided"]
    g["moving"].pop(who, None)
    if r["hours"] <= geo.get("same_scene_hours", 12):
        if who == PLAYER:
            g["player"] = goal
        else:
            g["positions"][who] = goal
        result["arrived"] = True
        return result
    days = math.ceil(r["hours"] / 24)
    if who == PLAYER:
        g["player"] = goal
        result["arrived"] = True
        result["days"] = days
        result["note"] = f"The journey takes {days} day(s): pass days_elapsed={days} in propose_state_update when this beat closes."
        return result
    g["moving"][who] = {"to": goal, "path": r["path"], "legs": [list(l) for l in r["legs"]],
                        "hours_left": r["hours"], "departed": state.get("date"),
                        "eta": _add_days(state["date"], days) if state.get("date") else None}
    result["arrived"] = False
    result["eta"] = g["moving"][who]["eta"]
    return result


def blocks_near(geo, state, start, goal, who):
    """Why there's no route: the closed or held edges a free route would have used."""
    saved = (state.get("geo") or {}).get("edges")
    state["geo"]["edges"] = {}
    try:
        free = route(geo, state, start, goal, who)
    finally:
        state["geo"]["edges"] = saved
    if not free:
        return []
    out = []
    for eid, how, _ in free["legs"]:
        ok, why = _passable(state, eid, geo["edges"][eid], how, side_of(state, who))
        if not ok:
            out.append(why)
    return out


def tick_day(geo, state, hours=24.0):
    """One day passes: units on the road cover a day's travel. A unit whose next leg has been closed
    since it set out stops at the last place it reached. Returns change records."""
    g = ensure_initialized(state, geo)
    if not g:
        return []
    changes = []
    for uid, mv in list(g["moving"].items()):
        budget = hours
        side = side_of(state, uid)
        node = g["positions"].get(uid, mv["path"][0])
        while mv["legs"] and budget > 0:
            eid, how, leg_hours = mv["legs"][0]
            ok, why = (True, None) if eid == "muster" else _passable(state, eid, geo["edges"][eid], how, side)
            if not ok:
                g["moving"].pop(uid)
                g["positions"][uid] = node
                changes.append({"kind": "movement", "unit": uid, "status": "halted", "at": node,
                                "message": f"{_uname(state, uid)} halted at {place_name(geo, node)}: {why}."})
                break
            if leg_hours > budget:
                mv["legs"][0][2] = leg_hours - budget
                mv["hours_left"] = max(0.0, mv["hours_left"] - budget)
                budget = 0
                break
            budget -= leg_hours
            mv["hours_left"] = max(0.0, mv["hours_left"] - leg_hours)
            mv["legs"].pop(0)
            if eid == "muster":
                continue
            e = geo["edges"][eid]
            node = e["b"] if e["a"] == node else e["a"]
            g["positions"][uid] = node
        if uid in g["moving"] and not mv["legs"]:
            g["moving"].pop(uid)
            g["positions"][uid] = mv["to"]
            changes.append({"kind": "movement", "unit": uid, "status": "arrived", "at": mv["to"],
                            "message": f"{_uname(state, uid)} arrived at {place_name(geo, mv['to'])}."})
    changes += run_schedule(geo, state)
    return changes


# ---------------------------------------------------------------- units appearing, merging, splitting

MAX_RAISE = 3000          # men raised in one go
RAISE_COOLDOWN_DAYS = 3   # per place
MAX_RAISE_READINESS = 2   # new levies are green


def _tracker_for(geo, state, node):
    """Which forces tracker a new unit at this place belongs in: the city's, or the country's."""
    forces = [iid for iid, m in (state.get("mechanics") or {}).items() if m.get("render_primitive") == "forces"]
    want = "petrograd_garrison" if geo["nodes"].get(node, {}).get("scale") == "city" else "russia_forces"
    return want if want in forces else (forces[0] if forces else None)


def _new_id(state, name):
    base = "_".join(_norm(name).split())[:40] or "unit"
    uid, n = base, 2
    while uid in force_units(state):
        uid, n = f"{base}_{n}", n + 1
    return uid


def _add_unit(state, iid, unit):
    state["mechanics"][iid]["data"]["units"].append(unit)


def _remove_unit(state, uid):
    iid, u = find_unit(state, uid)
    if iid:
        m = state["mechanics"][iid]["data"]
        m["units"] = [x for x in m["units"] if x["id"] != uid]
        if not m["units"]:  # a forces tracker must keep at least one unit to stay valid
            m["units"] = [u | {"strength": 0, "note": "disbanded"}]
    g = state.get("geo") or {}
    (g.get("positions") or {}).pop(uid, None)
    (g.get("moving") or {}).pop(uid, None)


def _together(geo, state, uids):
    """All present (not marching) and within a short walk of the first one's place."""
    g = state["geo"]
    first = g["positions"].get(uids[0])
    for uid in uids:
        if uid in g["moving"]:
            return None, f"{_uname(state, uid)} is on the move."
        at = g["positions"].get(uid)
        if at is None:
            return None, f"{_uname(state, uid)} isn't on the map yet - place it with move_unit."
        if at != first:
            r = route(geo, state, at, first, uid)
            if not r or r["hours"] > ACT_HOURS:
                return None, f"{_uname(state, uid)} is at {place_name(geo, at)}, not with {_uname(state, uids[0])} at {place_name(geo, first)}."
    return first, None


def reorganize(geo, state, inp):
    """raise / merge / split / disband. Code does the arithmetic and checks everyone is where they
    need to be; the GM supplies the fiction."""
    ensure_initialized(state, geo)
    action = inp.get("action")
    g = state["geo"]
    if action == "raise":
        node, err = resolve_place(geo, state, inp.get("at"))
        if err:
            return {"error": err}
        recent = [r for r in g.setdefault("raised", []) if r["at"] == node and state.get("date") and r["date"] >= _add_days(state["date"], -RAISE_COOLDOWN_DAYS)]
        if recent:
            return {"error": f"Men were already raised at {place_name(geo, node)} on {recent[-1]['date']}; wait a few days or raise them elsewhere."}
        iid = _tracker_for(geo, state, node)
        if not iid:
            return {"error": "No forces tracker to add the unit to."}
        name = (inp.get("name") or "").strip()
        if not name:
            return {"error": "A new unit needs a name."}
        strength = max(50, min(MAX_RAISE, int(inp.get("strength") or 500)))
        unit = {"id": _new_id(state, name), "name": name, "kind": str(inp.get("kind") or "militia"),
                "strength": strength, "readiness": max(1, min(MAX_RAISE_READINESS, int(inp.get("readiness") or 1))),
                "loyalty": max(-3, min(3, int(inp.get("loyalty") if inp.get("loyalty") is not None else 2))),
                "note": str(inp.get("note") or inp.get("reasoning") or "")}
        _add_unit(state, iid, unit)
        g["positions"][unit["id"]] = node
        g["raised"] = (g["raised"] + [{"at": node, "date": state.get("date")}])[-30:]
        out = {"raised": unit, "at": place_name(geo, node), "tracker": iid}
        if strength < int(inp.get("strength") or 0):
            out["note"] = f"Capped at {MAX_RAISE} men per raising; raise again elsewhere or in a few days."
        return out
    if action == "merge":
        uids = list(dict.fromkeys(inp.get("units") or []))
        if len(uids) < 2:
            return {"error": "merge needs two or more unit ids."}
        found = [find_unit(state, u) for u in uids]
        missing = [u for u, (iid, _) in zip(uids, found) if not iid]
        if missing:
            return {"error": f"Unknown units {missing}."}
        node, err = _together(geo, state, uids)
        if err:
            return {"error": err}
        parts = [u for _, u in found]
        total = sum(u["strength"] for u in parts) or 1
        keep = parts[0]
        merged = {
            "strength": total,
            "readiness": max(1, min(5, int(sum(u["readiness"] * u["strength"] for u in parts) / total))),
            "loyalty": max(-3, min(3, round(sum(u["loyalty"] * u["strength"] for u in parts) / total))),
        }
        for u in parts[1:]:
            _remove_unit(state, u["id"])
        keep.update(merged)
        if inp.get("name"):
            keep["name"] = inp["name"]
        keep["note"] = (keep.get("note", "") + f" Merged with {', '.join(u['name'] for u in parts[1:])} ({state.get('date')}).").strip()
        return {"merged_into": keep["id"], "name": keep["name"], "at": place_name(geo, node), **merged,
                "note": "Readiness and loyalty are the strength-weighted average - a keen unit absorbing a slack one loses its edge."}
    if action == "split":
        iid, u = find_unit(state, inp.get("unit"))
        if not iid:
            return {"error": f"Unknown unit '{inp.get('unit')}'."}
        node, err = _together(geo, state, [u["id"]])
        if err:
            return {"error": err}
        n = int(inp.get("strength") or 0)
        if not 0 < n < u["strength"]:
            return {"error": f"Detach between 1 and {u['strength'] - 1} men."}
        name = (inp.get("name") or f"{u['name']} detachment").strip()
        new = {k: u[k] for k in ("kind", "readiness", "loyalty")} | {
            "id": _new_id(state, name), "name": name, "strength": n, "note": f"Detached from {u['name']} ({state.get('date')})."}
        u["strength"] -= n
        _add_unit(state, iid, new)
        g["positions"][new["id"]] = node
        return {"split_from": u["id"], "new_unit": new, "remaining": u["strength"], "at": place_name(geo, node)}
    if action == "disband":
        iid, u = find_unit(state, inp.get("unit"))
        if not iid:
            return {"error": f"Unknown unit '{inp.get('unit')}'."}
        _remove_unit(state, u["id"])
        return {"disbanded": u["id"], "name": u["name"], "reason": inp.get("reasoning") or ""}
    return {"error": "action must be raise, merge, split or disband."}


def _schedule_ok(state, item):
    cond = item.get("if") or {}
    uid = item.get("unit") if isinstance(item.get("unit"), str) else None
    if uid:
        _, u = find_unit(state, uid)
        if not u or u.get("strength", 0) <= 0:
            return False
        if "loyalty_max" in cond and u["loyalty"] > cond["loyalty_max"]:
            return False
        if "loyalty_min" in cond and u["loyalty"] < cond["loyalty_min"]:
            return False
    return True


def run_schedule(geo, state):
    """Historical defaults for units the player isn't driving (geography.json "scheduled"). Each item
    fires once on its date if its unit still exists and still fits the condition - so a campaign that
    has already won the Czechoslovaks over, or destroyed the Tekke regiment, doesn't get history."""
    g = state["geo"]
    today = state.get("date") or ""
    changes = []
    for item in geo.get("scheduled") or []:
        if item["id"] in g["schedule_done"] or item["date"] > today:
            continue
        g["schedule_done"].append(item["id"])
        if not _schedule_ok(state, item):
            continue
        act, msg = item["action"], item.get("message", "")
        if act == "appear":
            unit = dict(item["unit"])
            if unit["id"] in force_units(state):
                continue
            node = item["at"]
            iid = _tracker_for(geo, state, node)
            if not iid:
                continue
            _add_unit(state, iid, unit)
            g["positions"][unit["id"]] = node
        elif act == "move":
            res = move(geo, state, item["unit"], item["to"], foot_only=bool(item.get("foot_only")))
            if "error" in res:
                continue
        elif act == "reinforce":
            _, u = find_unit(state, item["unit"])
            u["strength"] += int(item.get("strength_add", 0))
            if item.get("name"):
                u["name"] = item["name"]
        elif act == "split":
            iid, u = find_unit(state, item["unit"])
            n = min(int(item["strength"]), u["strength"] - 1)
            if n <= 0:
                continue
            new = {k: u[k] for k in ("kind", "readiness")} | {"strength": n, "note": msg, **item["new"]}
            u["strength"] -= n
            if "loyalty" in item:
                u["loyalty"] = new["loyalty"] = item["loyalty"]
            else:
                new["loyalty"] = u["loyalty"]
            _add_unit(state, iid, new)
            g["positions"][new["id"]] = item.get("at") or g["positions"].get(u["id"])
        changes.append({"kind": "movement", "status": "history", "unit": item.get("unit") if isinstance(item.get("unit"), str) else item["unit"]["id"],
                        "message": msg})
    return changes


# ---------------------------------------------------------------- bridges, lines, pickets

def resolve_edge(geo, state, text):
    """An edge from an id, a bridge's name, or 'Place A - Place B' for two adjacent places."""
    if not text:
        return None, "no route given"
    if text in geo["edges"]:
        return text, None
    key = _norm(text)
    named = [eid for eid, e in geo["edges"].items() if e.get("name") and e["mode"] == "bridge"
             and (_norm(e["name"]) == key or _norm(e["name"]).startswith(key) or key.startswith(_norm(e["name"])))]
    if len(named) == 1:
        return named[0], None
    for sep in (" - ", " to ", "-", "–", "—"):
        if sep in str(text):
            left, right = [s.strip() for s in str(text).split(sep, 1)]
            a, err_a = resolve_place(geo, state, left)
            b, err_b = resolve_place(geo, state, right)
            if a and b:
                for eid, nxt in geo["_adj"][a]:
                    if nxt == b:
                        return eid, None
                return None, f"{place_name(geo, a)} and {place_name(geo, b)} aren't directly connected; name one leg (two neighbouring stations or a bridge)."
    bridges = sorted(e["name"] for e in geo["edges"].values() if e["mode"] == "bridge")
    return None, f"Unknown route '{text}'. Bridges: {', '.join(bridges)}. For a railway or road leg write 'Place A - Place B'."


def _near(geo, state, who, nodes, limit):
    g = state.get("geo") or {}
    at = g.get("player") if who == PLAYER else (g.get("positions") or {}).get(who)
    if at is None or who in (g.get("moving") or {}):
        return False
    for n in nodes:
        r = route(geo, state, at, n, who)
        if r and r["hours"] <= limit:
            return True
    return False


def set_edge(geo, state, edge_text, status, by=None, hold=None, reason=""):
    """Raise/lower a bridge, cut/repair a line, block a road, or put a picket on it (hold=True) or
    take one off (hold=False). Whoever does it must be at one end - code checks."""
    g = ensure_initialized(state, geo)
    eid, err = resolve_edge(geo, state, edge_text)
    if err:
        return {"error": err}
    e = geo["edges"][eid]
    name = e.get("name") or f"{place_name(geo, e['a'])} - {place_name(geo, e['b'])}"
    if status and status not in STATUSES:
        return {"error": f"status must be one of {sorted(STATUSES)}"}
    if status == "raised" and not e.get("raisable"):
        return {"error": f"{name} can't be raised."}
    if status == "cut" and e["mode"] != "rail":
        status = "blocked"
    actor_ok = by == "railwaymen" and e["mode"] == "rail"
    if by and not actor_ok:
        if by != PLAYER and by not in force_units(state):
            return {"error": f"Unknown unit '{by}'."}
        if not _near(geo, state, by, [e["a"], e["b"]], ACT_HOURS):
            return {"error": f"{by} isn't at {name} (needs to be at one end, not on the move). Move it there first."}
    elif not by:
        return {"error": "Say who does it: a unit id at one end, 'player', or for a railway 'railwaymen'."}
    cur = dict(edge_state(state, eid))
    before = dict(cur)
    if status:
        cur["status"] = status
    if hold is True:
        if by in (PLAYER, "railwaymen"):
            return {"error": "A picket has to be a unit."}
        cur["held_by"] = by
    elif hold is False:
        cur.pop("held_by", None)
    cur.update({"by": by, "since": state.get("date"), "reason": reason})
    if cur.get("status", "open") == "open" and not cur.get("held_by"):
        g["edges"].pop(eid, None)
    else:
        g["edges"][eid] = cur
    return {"edge": eid, "name": name, "status": cur.get("status", "open"), "held_by": cur.get("held_by"),
            "before": {k: before.get(k) for k in ("status", "held_by") if before.get(k)}}


# ---------------------------------------------------------------- confrontations

def presence(geo, state, place_text, unit_ids):
    """Which of these units can be at a fight at this place. Returns (node, present ids,
    {absent id: why}) or (None, [], {}, error)."""
    ensure_initialized(state, geo)
    node, err = resolve_place(geo, state, place_text)
    if err:
        return None, [], {}, err
    g = state["geo"]
    present, absent = [], {}
    for uid in unit_ids:
        if uid in g["moving"]:
            mv = g["moving"][uid]
            absent[uid] = f"on the move to {place_name(geo, mv['to'])}" + (f" (due {mv['eta']})" if mv.get("eta") else "")
            continue
        at = g["positions"].get(uid)
        if at is None:
            present.append(uid)  # never placed: give the GM the benefit of the doubt
            continue
        r = route(geo, state, at, node, uid)
        if r and r["hours"] <= REACH_HOURS:
            present.append(uid)
        else:
            absent[uid] = (f"at {place_name(geo, at)}, {fmt_hours(r['hours'])} away" if r
                           else f"at {place_name(geo, at)}, cut off ({'; '.join(blocks_near(geo, state, at, node, uid)) or 'no way through'})")
    return node, present, absent, None


def after_confrontation(geo, state, node, inp, result):
    """Whoever attacked and won now holds the place: their units are moved onto it."""
    import operations  # local: operations has no need to know about geography
    if node is None:
        return []
    outcome = result.get("player_outcome")
    attacking = bool(inp.get("player_side_attacking"))
    if attacking and outcome in operations.PLAYER_WIN_OUTCOMES:
        winners = inp.get("player_units") or []
    elif not attacking and outcome in operations.PLAYER_LOSS_OUTCOMES:
        winners = inp.get("opposing_units") or []
    else:
        return []
    g = state["geo"]
    moved = [uid for uid in winners if uid in force_units(state) and g["positions"].get(uid) != node]
    for uid in moved:
        g["positions"][uid] = node
        g["moving"].pop(uid, None)
    return [{"kind": "movement", "unit": uid, "status": "arrived", "at": place_name(geo, node),
             "message": f"{_uname(state, uid)} holds {place_name(geo, node)}."} for uid in moved]


